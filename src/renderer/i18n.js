  let currentLang = 'pl';

  function t(key, vars = {}) {
    const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.pl;
    let text = dict[key] !== undefined ? dict[key] : TRANSLATIONS.pl[key] !== undefined ? TRANSLATIONS.pl[key] : key;
    for (const [k, v] of Object.entries(vars || {})) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
    return text;
  }

  function applyDomTranslations(root = document) {
    root.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
    });
    root.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.setAttribute('title', t(el.dataset.i18nTitle));
    });
  }

  function setLanguage(code) {
    currentLang = TRANSLATIONS[code] ? code : 'pl';
    document.documentElement.lang = currentLang;
    applyDomTranslations();
    return currentLang;
  }

  window.PeakI18n = {
    LANGUAGES,
    setLanguage,
    getLanguage: () => currentLang,
    t,
    applyDomTranslations
  };
